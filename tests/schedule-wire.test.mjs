import assert from "node:assert/strict";
import {createHmac} from "node:crypto";
import {signScheduleCommand,V2_COMMAND_TOPIC,V2_DEVICE} from "../backend/schedule-wire.mjs";
const key=new Uint8Array(Array.from({length:32},(_,i)=>i+1));
const command="BEGIN|request123|0000000000000000|1234567890abcdef|2|9da28728af57c536";
const frame=await signScheduleCommand({key,sequence:1001,command});
const fields=frame.split("|");
assert.equal(fields.length,4);
assert.equal(fields[0],"V2");
assert.equal(fields[1],"1001");
assert.equal(Buffer.from(fields[2],"base64").toString(),command);
const canonical="T4M-V2\n"+V2_DEVICE+"\n"+V2_COMMAND_TOPIC+"\n1001\n"+fields[2];
assert.equal(fields[3],createHmac("sha256",key).update(canonical).digest("hex"));
assert.match(fields[3],/^[0-9a-f]{64}$/);
const wrong=async args=>assert.rejects(()=>signScheduleCommand(args));
await wrong({key:new Uint8Array(8),sequence:1001,command});
await wrong({key,sequence:0,command});
await wrong({key,sequence:2,topic:"time4med/v1/cabinet/cabinet-01/command/schedule",command});
await wrong({key,sequence:2,deviceId:"OTHER",command});
await wrong({key,sequence:2,command:"CLEAR|U002\nbad"});
await wrong({key,sequence:2,command:"A".repeat(129)});
console.log("PASS: signed MQTT command envelope uses HMAC-SHA256 with exact device/topic and sequence binding");
